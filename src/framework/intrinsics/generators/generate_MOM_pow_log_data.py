"""Generate logarithm tails for MOM_pow from the existing log table.

Run from src/framework/intrinsics:
  python3 generators/generate_MOM_pow_log_data.py > MOM_pow_log_data.F90

Decimal arithmetic at 100 decimal digits computes -log(inv_c) - log_c,
using the exact binary64 values of the existing table entries. No changes
to the standalone logarithm's tables or answers are required.
"""

from decimal import Decimal, localcontext
from pathlib import Path
import re


def table(source, name):
    """Read the binary64 entries of one generated Fortran array."""
    body = re.search(rf":: {name}\(0:ndiv-1\) = \[ &(.*?)\]", source, re.S)[1]
    return [Decimal.from_float(float(x)) for x in
            re.findall(r"[-+]?\d+\.\d+e[-+]\d+", body)]


def main():
    source = (Path(__file__).resolve().parent.parent / "MOM_log_data_n128.F90").read_text()
    reciprocals = table(source, "inv_c")
    logarithms = table(source, "log_c")
    assert len(reciprocals) == len(logarithms) == 128
    with localcontext() as context:
        context.prec = 100
        tails = [float(-r.ln() - c) for r, c in zip(reciprocals, logarithms)]
    print("""! This file is part of MOM6, the Modular Ocean Model version 6.
! See the LICENSE file for licensing information.
! SPDX-License-Identifier: Apache-2.0

!> Low-order logarithm table for compensated power evaluation.
!! Generated by generators/generate_MOM_pow_log_data.py from MOM_log_data_n128.
module MOM_pow_log_data

implicit none ; private
public :: log_c_tail

!> Residual -log(inv_c) - log_c for the existing binary64 log table [nondim]
real, parameter :: log_c_tail(0:127) = [ &""")
    for start in range(0, 128, 4):
        end = ", &" if start < 124 else " &"
        print("    " + ", ".join(f"{x: .17e}" for x in tails[start:start + 4]) + end)
    print("]\n\nend module MOM_pow_log_data")


if __name__ == "__main__":
    main()
